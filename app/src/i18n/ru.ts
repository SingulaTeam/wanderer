/** Russian plural forms: one, few, many. */
function plural(n: number, one: string, few: string, many: string): string {
	const tens = n % 100;
	const units = n % 10;
	if (tens >= 11 && tens <= 14) return many;
	if (units === 1) return one;
	if (units >= 2 && units <= 4) return few;
	return many;
}

